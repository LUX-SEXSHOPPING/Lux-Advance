-- ============================================================
-- CRIAÇÃO AUTOMÁTICA DO PERFIL
-- ============================================================

create or replace function public.handle_novo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare

  v_tipo text := coalesce(
    new.raw_user_meta_data->>'tipo',
    'usuario'
  );

  v_nome text := coalesce(
    new.raw_user_meta_data->>'nome',
    'Usuário LUX'
  );

begin

  if v_tipo not in (
    'usuario',
    'modelo'
  ) then

    v_tipo := 'usuario';

  end if;


  insert into public.perfis(
    id,
    nome,
    tipo,
    status
  )
  values(
    new.id,
    v_nome,
    v_tipo,

    case
      when v_tipo = 'modelo'
      then 'pendente'
      else 'ativo'
    end
  )

  on conflict (id)
  do nothing;


  if v_tipo = 'modelo' then

    insert into public.modelo_perfis(
      id,
      nome_exibicao,
      idade,
      cidade,
      pais,
      cor_cabelo,
      cor_olhos,
      altura_cm,
      idiomas,
      descricao,
      foto_url,
      maioridade_confirmada
    )

    values(

      new.id,

      v_nome,

      greatest(
        18,
        least(
          99,
          coalesce(
            (new.raw_user_meta_data->>'idade')::integer,
            18
          )
        )
      ),

      nullif(
        new.raw_user_meta_data->>'cidade',
        ''
      ),

      coalesce(
        nullif(
          new.raw_user_meta_data->>'pais',
          ''
        ),
        'Brasil'
      ),

      nullif(
        new.raw_user_meta_data->>'cor_cabelo',
        ''
      ),

      nullif(
        new.raw_user_meta_data->>'cor_olhos',
        ''
      ),

      case

        when (
          new.raw_user_meta_data->>'altura_cm'
        ) ~ '^[0-9]+$'

        then (
          new.raw_user_meta_data->>'altura_cm'
        )::integer

        else null

      end,

      nullif(
        new.raw_user_meta_data->>'idiomas',
        ''
      ),

      left(
        nullif(
          new.raw_user_meta_data->>'descricao',
          ''
        ),
        800
      ),

      nullif(
        new.raw_user_meta_data->>'foto_url',
        ''
      ),

      coalesce(
        (
          new.raw_user_meta_data->
          >'maioridade_confirmada'
        )::boolean,
        false
      )

    )

    on conflict (id)

    do update set

      nome_exibicao =
        excluded.nome_exibicao,

      idade =
        excluded.idade,

      cidade =
        excluded.cidade,

      pais =
        excluded.pais,

      cor_cabelo =
        excluded.cor_cabelo,

      cor_olhos =
        excluded.cor_olhos,

      altura_cm =
        excluded.altura_cm,

      idiomas =
        excluded.idiomas,

      descricao =
        excluded.descricao,

      foto_url =
        excluded.foto_url,

      maioridade_confirmada =
        excluded.maioridade_confirmada;

  end if;


  return new;

end;
$$;


