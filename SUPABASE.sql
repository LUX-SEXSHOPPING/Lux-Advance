drop function if exists public.ativar_plano_gratuito(text);
create or replace function public.ativar_plano_gratuito(p_plano text)
returns void language plpgsql security definer set search_path=public as $$
begin
  if p_plano <> 'ESSENCE' then raise exception 'Plano inválido'; end if;
  if not exists(select 1 from public.perfis where id=auth.uid() and tipo='modelo') then raise exception 'Somente modelos podem ativar planos'; end if;
  update public.modelo_perfis set plano_codigo='ESSENCE', plano_nome='LUX-ESSENCE', plano_status='ativo', selo_codigo='ESSENCE', plano_inicio=now(), plano_expira_em=null, mp_subscription_id=null, atualizado_em=now() where id=auth.uid();
end; $$;
grant execute on function public.ativar_plano_gratuito(text) to authenticated;

-- Reforça os valores públicos dos selos para que sejam exibidos no perfil publicado.
comment on column public.modelo_perfis.selo_codigo is 'Selo público do plano: ESSENCE, VERIFICADO, ELITE ou ROYAL';

-- SEGURANÇA: plano e selo são controlados pelo servidor/webhook.
-- Modelos não podem alterar manualmente benefícios premium pelo cliente.
drop trigger if exists proteger_plano_modelo on public.modelo_perfis;
create or replace function public.proteger_plano_modelo()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
begin
  if coalesce(auth.role(),'') <> 'service_role' and coalesce(public.meu_tipo(),'') <> 'admin' then
    -- O cliente pode permanecer/voltar ao plano gratuito, mas nunca
    -- pode atribuir a si mesmo VERIFICADO, ELITE ou ROYAL.
    if new.plano_codigo is distinct from old.plano_codigo
       or new.plano_nome is distinct from old.plano_nome
       or new.plano_status is distinct from old.plano_status
       or new.selo_codigo is distinct from old.selo_codigo
       or new.plano_inicio is distinct from old.plano_inicio
       or new.plano_expira_em is distinct from old.plano_expira_em
       or new.mp_subscription_id is distinct from old.mp_subscription_id then
      if not (new.plano_codigo='ESSENCE' and new.plano_nome='LUX-ESSENCE'
              and new.plano_status='ativo' and new.selo_codigo='ESSENCE'
              and new.plano_expira_em is null and new.mp_subscription_id is null) then
        raise exception 'Plano e selo são gerenciados automaticamente pelo LUX.';
      end if;
    end if;
  end if;
  return new;
end; $$;

create trigger proteger_plano_modelo
before update on public.modelo_perfis
for each row execute function public.proteger_plano_modelo();
