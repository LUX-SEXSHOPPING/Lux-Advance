-- LUX — MIGRAÇÃO COMPLETA DE CONTAS, MODELOS E AVALIAÇÕES
-- Não apaga tabelas existentes. Pode ser executado no SQL Editor.

create table if not exists public.perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  tipo text not null check (tipo in ('usuario','modelo','admin')),
  status text not null default 'ativo' check (status in ('ativo','pendente','aprovado','bloqueado')),
  created_at timestamptz default now()
);

alter table public.perfis enable row level security;

-- Novas informações da conta
alter table public.perfis add column if not exists updated_at timestamptz default now();

create table if not exists public.modelo_perfis (
  id uuid primary key references public.perfis(id) on delete cascade,
  nome_exibicao text not null,
  idade integer not null check (idade between 18 and 99),
  cidade text,
  pais text default 'Brasil',
  cor_cabelo text,
  cor_olhos text,
  altura_cm integer check (altura_cm between 100 and 230),
  idiomas text,
  descricao text check (char_length(coalesce(descricao,'')) <= 800),
  foto_url text,
  galeria_urls text[] default '{}',
  maioridade_confirmada boolean not null default false,
  verificacao_status text not null default 'pendente' check (verificacao_status in ('pendente','em_analise','verificada','reprovada')),
  estrelas_total integer not null default 0 check (estrelas_total >= 0),
  criado_em timestamptz default now(),
  atualizado_em timestamptz default now()
);

create table if not exists public.avaliacoes_modelos (
  id bigint generated by default as identity primary key,
  modelo_id uuid not null references public.modelo_perfis(id) on delete cascade,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  valor smallint not null default 1 check (valor = 1),
  created_at timestamptz default now(),
  unique(modelo_id, usuario_id)
);

alter table public.modelo_perfis enable row level security;
alter table public.avaliacoes_modelos enable row level security;

-- Função segura para identificar o tipo sem expor privilégios.
create or replace function public.meu_tipo()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select tipo from public.perfis where id = auth.uid();
$$;

-- Criação automática do perfil logo após o cadastro no Auth.
create or replace function public.handle_novo_usuario()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tipo text := coalesce(new.raw_user_meta_data->>'tipo','usuario');
  v_nome text := coalesce(new.raw_user_meta_data->>'nome','Usuário LUX');
begin
  if v_tipo not in ('usuario','modelo') then v_tipo := 'usuario'; end if;
  insert into public.perfis(id,nome,tipo,status)
  values(new.id,v_nome,v_tipo,case when v_tipo='modelo' then 'pendente' else 'ativo' end)
  on conflict (id) do nothing;
  if v_tipo='modelo' then
    insert into public.modelo_perfis(
      id,nome_exibicao,idade,cidade,pais,cor_cabelo,cor_olhos,altura_cm,idiomas,descricao,foto_url,maioridade_confirmada
    )
    values(
      new.id,
      v_nome,
      greatest(18, least(99, coalesce((new.raw_user_meta_data->>'idade')::integer,18))),
      nullif(new.raw_user_meta_data->>'cidade',''),
      coalesce(nullif(new.raw_user_meta_data->>'pais',''),'Brasil'),
      nullif(new.raw_user_meta_data->>'cor_cabelo',''),
      nullif(new.raw_user_meta_data->>'cor_olhos',''),
      case when (new.raw_user_meta_data->>'altura_cm') ~ '^[0-9]+$' then (new.raw_user_meta_data->>'altura_cm')::integer else null end,
      nullif(new.raw_user_meta_data->>'idiomas',''),
      left(nullif(new.raw_user_meta_data->>'descricao',''),800),
      nullif(new.raw_user_meta_data->>'foto_url',''),
      coalesce((new.raw_user_meta_data->>'maioridade_confirmada')::boolean,false)
    )
    on conflict (id) do update set
      nome_exibicao=excluded.nome_exibicao, idade=excluded.idade, cidade=excluded.cidade, pais=excluded.pais,
      cor_cabelo=excluded.cor_cabelo, cor_olhos=excluded.cor_olhos, altura_cm=excluded.altura_cm, idiomas=excluded.idiomas,
      descricao=excluded.descricao, foto_url=excluded.foto_url, maioridade_confirmada=excluded.maioridade_confirmada;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_novo_usuario();

-- Recalcula o total de estrelas sem permitir edição manual pelo usuário.
create or replace function public.recalcular_estrelas_modelo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.modelo_perfis mp
  set estrelas_total = (select count(*) from public.avaliacoes_modelos a where a.modelo_id = mp.id),
      atualizado_em = now()
  where mp.id = coalesce(new.modelo_id, old.modelo_id);
  return coalesce(new, old);
end;
$$;

drop trigger if exists trg_recalcular_estrelas on public.avaliacoes_modelos;
create trigger trg_recalcular_estrelas
after insert or delete on public.avaliacoes_modelos
for each row execute function public.recalcular_estrelas_modelo();

