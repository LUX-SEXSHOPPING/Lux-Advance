create policy "perfil proprio select"
on public.perfis for select to authenticated
using (auth.uid() = id or public.meu_tipo() = 'admin');

create policy "perfil proprio update"
on public.perfis for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id and tipo in ('usuario','modelo'));

create policy "admin gerencia perfis"
on public.perfis for update to authenticated
using (public.meu_tipo() = 'admin')
with check (public.meu_tipo() = 'admin');

create policy "modelos aprovados publicos"
on public.modelo_perfis for select to anon, authenticated
using (verificacao_status = 'verificada' and (select status from public.perfis where id = modelo_perfis.id) in ('aprovado','ativo'));

create policy "modelo ve proprio cadastro"
on public.modelo_perfis for select to authenticated
using (auth.uid() = id or public.meu_tipo() = 'admin');

create policy "modelo atualiza cadastro"
on public.modelo_perfis for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id and idade >= 18 and maioridade_confirmada = true);

create policy "admin gerencia modelos"
on public.modelo_perfis for all to authenticated
using (public.meu_tipo() = 'admin')
with check (public.meu_tipo() = 'admin');

create policy "modelo cria cadastro"
on public.modelo_perfis for insert to authenticated
with check (auth.uid() = id and idade >= 18 and maioridade_confirmada = true);

create policy "usuario pode ver avaliacoes"
on public.avaliacoes_modelos for select to anon, authenticated
using (true);

create policy "usuario pode avaliar uma vez"
on public.avaliacoes_modelos for insert to authenticated
with check (auth.uid() = usuario_id and valor = 1 and exists (
  select 1 from public.perfis p where p.id = auth.uid() and p.tipo = 'usuario' and p.status = 'ativo'
) and exists (
  select 1 from public.modelo_perfis m where m.id = modelo_id and m.verificacao_status = 'verificada'
));

