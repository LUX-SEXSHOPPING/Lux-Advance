create or replace function
public.ativar_plano_gratuito(
  p_plano text
)

returns void

language plpgsql

security definer

set search_path = public

as $$
begin

  -- Aceita tanto ESSENCE quanto
  -- LUX-ESSENCE para compatibilidade.

  if p_plano not in (
    'ESSENCE',
    'LUX-ESSENCE'
  ) then

    raise exception
      'Plano gratuito inválido';

  end if;


  if not exists (

    select 1

    from public.perfis

    where id = auth.uid()

      and tipo = 'modelo'

  ) then

    raise exception
      'Somente modelos podem ativar planos';

  end if;


  update public.modelo_perfis

  set

    plano_codigo =
      'ESSENCE',

    plano_nome =
      'LUX-ESSENCE',

    plano_status =
      'ativo',

    selo_codigo =
      'ESSENCE',

    plano_inicio =
      now(),

    plano_expira_em =
      null,

    mp_subscription_id =
      null,

    atualizado_em =
      now()

  where id =
    auth.uid();

end;
$$;


grant execute
on function
public.ativar_plano_gratuito(text)
to authenticated;


