on public.modelo_perfis;


create or replace function
public.proteger_plano_modelo()

returns trigger

language plpgsql

security definer

set search_path = public

as $$
begin

  if coalesce(
       auth.role(),
       ''
     ) <> 'service_role'

     and coalesce(
       public.meu_tipo(),
       ''
     ) <> 'admin'

  then

    if

      new.plano_codigo
      is distinct from
      old.plano_codigo

      or

      new.plano_nome
      is distinct from
      old.plano_nome

      or

      new.plano_status
      is distinct from
      old.plano_status

      or

      new.selo_codigo
      is distinct from
      old.selo_codigo

      or

      new.plano_inicio
      is distinct from
      old.plano_inicio

      or

      new.plano_expira_em
      is distinct from
      old.plano_expira_em

      or

      new.mp_subscription_id
      is distinct from
      old.mp_subscription_id

    then

      /*
        O cliente não pode atribuir
        manualmente um plano premium.

        O DIAMOND será ativado pelo
        fluxo autorizado de pagamento/
        webhook.
      */

      if not (

        new.plano_codigo =
          'ESSENCE'

        and new.plano_nome =
          'LUX-ESSENCE'

        and new.plano_status =
          'ativo'

        and new.selo_codigo =
          'ESSENCE'

        and new.plano_expira_em
          is null

        and new.mp_subscription_id
          is null

      ) then

        raise exception
          'Plano e selo são gerenciados automaticamente pelo LUX.';

      end if;

    end if;

  end if;


  return new;

end;
$$;


create trigger
proteger_plano_modelo

before update
on public.modelo_perfis

for each row

execute function
public.proteger_plano_modelo();


