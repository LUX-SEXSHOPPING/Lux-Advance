create or replace function
public.recalcular_estrelas_modelo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin

  update public.modelo_perfis mp

  set

    estrelas_total = (
      select count(*)
      from public.avaliacoes_modelos a
      where a.modelo_id = mp.id
    ),

    atualizado_em = now()

  where mp.id =
    coalesce(
      new.modelo_id,
      old.modelo_id
    );

  return coalesce(
    new,
    old
  );

end;
$$;


