create table if not exists public.modelo_perfis (
  id uuid primary key
    references public.perfis(id)
    on delete cascade,

  nome_exibicao text not null,

  idade integer not null
    check (idade between 18 and 99),

  cidade text,

  pais text default 'Brasil',

  cor_cabelo text,

  cor_olhos text,

  altura_cm integer
    check (altura_cm between 100 and 230),

  idiomas text,

  descricao text
    check (
      char_length(
        coalesce(descricao,'')
      ) <= 800
    ),

  foto_url text,

  galeria_urls text[]
    default '{}',

  maioridade_confirmada boolean
    not null default false,

  verificacao_status text
    not null default 'pendente'
    check (
      verificacao_status in (
        'pendente',
        'em_analise',
        'verificada',
        'reprovada'
      )
    ),

  estrelas_total integer
    not null default 0
    check (estrelas_total >= 0),

  criado_em timestamptz
    default now(),

  atualizado_em timestamptz
    default now()
);

